void saveProgress(const Progress& p) {
    ofstream f("cpp_progress.dat");
    if (!f) return;
    f << "streak=" << p.streak << "\n";
    f << "lastVisit=" << (long long)p.lastVisit << "\n";
    f << "totalLessons=" << p.totalLessons << "\n";
    for (auto& kv : p.completedLessons)
        if (kv.second) f << "lesson=" << kv.first << "\n";
    for (auto& kv : p.quizScores)
        f << "quiz=" << kv.first << "=" << kv.second << "\n";
    f.close();
}

Progress loadProgress() {
    Progress p;
    p.streak = 0;
    p.lastVisit = 0;
    p.totalLessons = 0;
    ifstream f("cpp_progress.dat");
    if (!f) return p;
    string line;
    while (getline(f, line)) {
        if (line.substr(0, 7) == "streak=")
            p.streak = stoi(line.substr(7));
        else if (line.substr(0, 10) == "lastVisit=")
            p.lastVisit = (time_t)stoll(line.substr(10));
        else if (line.substr(0, 13) == "totalLessons=")
            p.totalLessons = stoi(line.substr(13));
        else if (line.substr(0, 7) == "lesson=")
            p.completedLessons[line.substr(7)] = true;
        else if (line.substr(0, 5) == "quiz=") {
            string rest = line.substr(5);
            size_t pos = rest.rfind('=');
            if (pos != string::npos) {
                string key = rest.substr(0, pos);
                int val = stoi(rest.substr(pos + 1));
                p.quizScores[key] = val;
            }
        }
    }
    f.close();
    return p;
}

void updateStreak(Progress& p) {
    time_t now = time(nullptr);
    if (p.lastVisit == 0) {
        p.streak = 1;
    }
    else {
        double diff = difftime(now, p.lastVisit);
        if (diff < 86400.0) {
            // same day, no change
        }
        else if (diff < 172800.0) {
            p.streak++;
        }
        else {
            p.streak = 1;
        }
    }
    p.lastVisit = now;
}

