int runQuiz(const vector<Question>& questions, const string& quizKey, Progress& progress) {
    if (questions.empty()) {
        cout << "Нет вопросов для этого теста.\n";
        return 0;
    }
    int correct = 0;
    for (int qi = 0; qi < (int)questions.size(); qi++) {
        const Question& q = questions[qi];
        printLine('=');
        cout << "[?] Вопрос " << (qi + 1) << "/" << questions.size() << ":\n";
        cout << q.text << "\n\n";
        for (int i = 0; i < (int)q.options.size(); i++) {
            cout << "  " << (i + 1) << ". " << q.options[i] << "\n";
        }
        cout << "\nВаш ответ (1-" << q.options.size() << "): ";
        int ans = 0;
        while (!(cin >> ans) || ans < 1 || ans >(int)q.options.size()) {
            cin.clear();
            cin.ignore(numeric_limits<streamsize>::max(), '\n');
            cout << "Введите число от 1 до " << q.options.size() << ": ";
        }
        cin.ignore(numeric_limits<streamsize>::max(), '\n');
        if (ans - 1 == q.correctAnswer) {
            cout << "\n[OK] Правильно!\n";
            correct++;
        }
        else {
            cout << "\n[!!!] Неправильно. Верный ответ: " << (q.correctAnswer + 1) << ". "
                << q.options[q.correctAnswer] << "\n";
        }
        cout << "[AI] Объяснение: " << q.explanation << "\n";
        pause();
    }
    int score = (int)((double)correct / questions.size() * 100);
    printLine('=');
    cout << "[DONE] Тест завершён! Правильно: " << correct << "/" << questions.size()
        << " (" << score << "%)\n";
    progress.quizScores[quizKey] = score;
    pause();
    return score;
}

