void printLine(char c = '=', int width = 60) {
    for (int i = 0; i < width; i++) cout << c;
    cout << "\n";
}

void printCentered(const string& text, int width = 60) {
    int len = (int)text.size();
    if (len >= width) { cout << text << "\n"; return; }
    int pad = (width - len) / 2;
    for (int i = 0; i < pad; i++) cout << ' ';
    cout << text << "\n";
}

