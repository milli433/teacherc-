string progressBar(int done, int total, int width = 20) {
    if (total == 0) return "[" + string(width, '-') + "] 0%";
    int filled = (int)((double)done / total * width);
    string bar = "[";
    for (int i = 0; i < width; i++) bar += (i < filled ? '=' : '-');
    bar += "] ";
    int pct = (int)((double)done / total * 100);
    bar += to_string(pct) + "%";
    return bar;
}

